# Phase 2 Gate 3: reconcile the attendance core schema with ADR 0007.
#
# - Attendance statuses become exactly PRESENT/ABSENT (enforced by check
#   constraints on AttendanceEntry and AttendanceCorrection).
# - AttendanceEntry gains an optional absence_note (ABSENT only).
# - AttendanceRegister gains a DRAFT/SUBMITTED status plus submitted_by and
#   submitted_at. Existing registers become DRAFT: none was submitted under
#   the ADR 0007 meaning of "submitted", so they mean "attendance started,
#   not officially taken" until Gate 4 submits them.
#
# Legacy LATE/EXCUSED values are NEVER converted automatically. If any entry
# or correction still holds one, this migration stops before changing the
# schema and lists the affected rows. Reconcile them by hand, then re-run:
#
#   1. python manage.py migrate core 0020
#   2. In `python manage.py shell`, decide the correct PRESENT/ABSENT value
#      for each listed row from the school's own records, e.g.:
#        from core.models import AttendanceEntry, AttendanceCorrection
#        AttendanceEntry.objects.filter(pk=<id>).update(status="PRESENT")
#        AttendanceCorrection.objects.filter(pk=<id>).update(
#            previous_status="ABSENT")
#   3. python manage.py migrate
#
# A disposable development database may instead be recreated.

